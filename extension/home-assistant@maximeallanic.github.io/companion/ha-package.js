// The Home Assistant package that turns the companion's sensors into controls (sliders, switches, buttons, scripts).
// Pure (no gi://): used by the preferences, which show it ready to copy, and by the tests.
// mobile_app entity ids depend on the device name and on the language the sensor names had at registration, so the
// package is generated from the ids Home Assistant really gave (the `companion-snapshot` key written by the extension)
// rather than written by hand. Every generated entity has a fixed id (default_entity_id), whatever its translated name.
import {_, format} from '../i18n.js';

// HA's slugify for the ASCII case (lower case, accents dropped, anything else -> "_"). Home Assistant transliterates
// other scripts too (unidecode); this one cannot, so a non-Latin device name gives an empty slug: the caller then uses
// the notify service name HA reports (notifyVerified) or tells the user to check it.
export function slugify(text) {
    return String(text ?? '').normalize('NFKD').replace(/\p{M}/gu, '').toLowerCase()
        .replace(/[^a-z0-9]+/g, '_').replace(/^_+|_+$/g, '');
}

// snapshot: {deviceName, notifyService, notifyVerified, entities: {sensor unique_id: entity_id}}.
export function readCompanionSnapshot(json) {
    let s;
    try {
        s = JSON.parse(json);
    } catch (_e) {
        return null;
    }
    if (!s || typeof s !== 'object' || typeof s.notifyService !== 'string' || !s.notifyService ||
        !s.entities || typeof s.entities !== 'object')
        return null;
    const entities = Object.fromEntries(Object.entries(s.entities)
        .filter(([k, v]) => typeof k === 'string' && typeof v === 'string' && /^[a-z_]+\.[a-z0-9_]+$/.test(v)));
    return {deviceName: typeof s.deviceName === 'string' ? s.deviceName : '', notifyService: s.notifyService,
        notifyVerified: s.notifyVerified === true, entities};
}

const q = text => JSON.stringify(String(text));  // a YAML double-quoted scalar

function notify(service, message, data = null) {
    const lines = [`          - action: notify.${service}`, '            data:', `              message: ${message}`];
    if (data) {
        lines.push('              data:');
        for (const [k, v] of Object.entries(data))
            lines.push(`                ${k}: ${v}`);
    }
    return lines;
}

// The package text, or null when the snapshot is unusable. prefix: object id prefix of the generated entities.
export function buildPackage(snapshot) {
    if (!snapshot)
        return null;
    const {deviceName, notifyService: svc, entities: e} = snapshot;
    const prefix = slugify(deviceName) || 'computer';
    const name = template => format(template, deviceName || prefix);
    const online = `binary_sensor.${prefix}_online`;
    const available = `        availability: "{{ is_state('${online}', 'on') }}"`;
    const out = [
        `# ${format(_('Controls for the computer "%s" (Hearth for Home Assistant).'), deviceName)}`,
        `# ${_('Generated by the extension preferences from the entity ids Home Assistant gave this computer.')}`,
        `# ${_('Save it as packages/gnome_computer.yaml in the Home Assistant configuration folder, then restart Home Assistant.')}`,
        'template:',
        '  - binary_sensor:',
        `      - name: ${q(name(_('%s online')))}`,
        `        unique_id: ${prefix}_online`,
        `        default_entity_id: ${online}`,
        '        device_class: connectivity',
    ];
    // The last contact is sent every 60 s: older than 3 minutes, the computer is off, asleep or offline.
    if (e.last_contact) {
        out.push('        state: >',
            `          {% set t = states('${e.last_contact}') | as_datetime(none) %}`,
            '          {{ t is not none and now() - t < timedelta(minutes=3) }}');
    } else {
        out.push('        state: "{{ false }}"');
    }

    const sliders = [['volume', 'volume', _('%s volume'), 'mdi:volume-high'],
        ['brightness', 'brightness', _('%s brightness'), 'mdi:brightness-6'],
        ['keyboard_backlight', 'keyboard_backlight', _('%s keyboard backlight'), 'mdi:keyboard-outline']]
        .filter(([uid]) => e[uid]);
    if (sliders.length)
        out.push('  - number:');
    for (const [uid, command, label, icon] of sliders) {
        out.push(`      - name: ${q(name(label))}`, `        unique_id: ${prefix}_${uid}_control`,
            `        default_entity_id: number.${prefix}_${uid}`, `        icon: ${icon}`,
            '        unit_of_measurement: "%"', '        min: 0', '        max: 100', '        step: 5', available,
            `        state: "{{ states('${e[uid]}') | int(0) }}"`, '        set_value:',
            ...notify(svc, `command_${command}`, {level: '"{{ value }}"'}));
    }

    const switches = [['muted', 'mute', _('%s mute'), 'mdi:volume-off', "is_state('X', 'on')"],
        ['do_not_disturb', 'do_not_disturb', _('%s do not disturb'), 'mdi:bell-off', "is_state('X', 'on')"],
        ['caffeine', 'caffeine', _('%s caffeine'), 'mdi:coffee', "is_state('X', 'on')"],
        ['screen_on', 'screen', _('%s screen'), 'mdi:monitor', "is_state('X', 'on')"]]
        .filter(([uid]) => e[uid]);
    if (switches.length || e.theme)
        out.push('  - switch:');
    for (const [uid, command, label, icon, test] of switches) {
        out.push(`      - name: ${q(name(label))}`, `        unique_id: ${prefix}_${uid}_control`,
            `        default_entity_id: switch.${prefix}_${command}`, `        icon: ${icon}`, available,
            `        state: "{{ ${test.replace('X', e[uid])} }}"`,
            '        turn_on:', ...notify(svc, `command_${command}`, {state: '"on"'}),
            '        turn_off:', ...notify(svc, `command_${command}`, {state: '"off"'}));
    }
    if (e.theme) {
        out.push(`      - name: ${q(name(_('%s dark style')))}`, `        unique_id: ${prefix}_dark_theme_control`,
            `        default_entity_id: switch.${prefix}_dark_theme`, '        icon: mdi:theme-light-dark', available,
            `        state: "{{ is_state('${e.theme}', 'dark') }}"`,
            '        turn_on:', ...notify(svc, 'command_theme', {theme: 'dark'}),
            '        turn_off:', ...notify(svc, 'command_theme', {theme: 'light'}));
    }

    const buttons = [['lock', _('%s lock'), 'mdi:lock', 'command_lock', null],
        ['play_pause', _('%s play or pause'), 'mdi:play-pause', 'command_media', {action: 'play_pause'}],
        ['next', _('%s next track'), 'mdi:skip-next', 'command_media', {action: 'next'}],
        ['previous', _('%s previous track'), 'mdi:skip-previous', 'command_media', {action: 'previous'}]];
    out.push('  - button:');
    for (const [id, label, icon, message, data] of buttons) {
        out.push(`      - name: ${q(name(label))}`, `        unique_id: ${prefix}_${id}`,
            `        default_entity_id: button.${prefix}_${id}`, `        icon: ${icon}`, available,
            '        press:', ...notify(svc, message, data));
    }

    // Refused while the screen is locked (result "refused" in the gnome_home_assistant_command event).
    out.push('', 'script:');
    for (const [id, field, label, description, example, message] of [
        ['open_url', 'url', _('%s: open a web address'), _('http or https address to open in the default browser'),
            'https://www.home-assistant.io', 'command_open_url'],
        ['launch_app', 'app', _('%s: launch an application'), _('Desktop file ID of the application'),
            'org.gnome.Nautilus.desktop', 'command_launch_app']]) {
        out.push(`  ${prefix}_${id}:`, `    alias: ${q(name(label))}`, '    mode: queued', '    fields:',
            `      ${field}:`, `        description: ${q(description)}`, '        required: true',
            `        example: ${example}`, '        selector:', '          text:', '    sequence:',
            ...notify(svc, message, {[field]: `"{{ ${field} }}"`}).map(l => l.slice(4)));
    }
    return `${out.join('\n')}\n`;
}
